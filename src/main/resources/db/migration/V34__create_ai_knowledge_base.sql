CREATE TABLE ai_knowledge_base (
    id BIGINT NOT NULL,
    name VARCHAR(100) NOT NULL,
    description VARCHAR(500) NULL,
    visibility VARCHAR(20) NOT NULL DEFAULT 'INTERNAL',
    enabled TINYINT NOT NULL DEFAULT 1,
    chunk_size INT NOT NULL DEFAULT 800,
    chunk_overlap INT NOT NULL DEFAULT 120,
    top_k INT NOT NULL DEFAULT 6,
    score_threshold DECIMAL(6,5) NOT NULL DEFAULT 0.30000,
    system_prompt VARCHAR(1000) NULL,
    document_count INT NOT NULL DEFAULT 0,
    chunk_count INT NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    created_by BIGINT NOT NULL,
    updated_by BIGINT NOT NULL,
    deleted TINYINT NOT NULL DEFAULT 0,
    version INT NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    KEY idx_ai_kb_enabled (enabled, visibility)
);

CREATE TABLE ai_knowledge_document (
    id BIGINT NOT NULL,
    knowledge_base_id BIGINT NOT NULL,
    file_id BIGINT NOT NULL,
    file_name VARCHAR(255) NOT NULL,
    content_type VARCHAR(128) NULL,
    file_size BIGINT NOT NULL,
    content_hash VARCHAR(64) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    chunk_count INT NOT NULL DEFAULT 0,
    error_message VARCHAR(1000) NULL,
    indexed_at TIMESTAMP NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    created_by BIGINT NOT NULL,
    updated_by BIGINT NOT NULL,
    deleted TINYINT NOT NULL DEFAULT 0,
    version INT NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    KEY idx_ai_kb_document (knowledge_base_id, status),
    CONSTRAINT fk_ai_kb_document_base FOREIGN KEY (knowledge_base_id) REFERENCES ai_knowledge_base (id),
    CONSTRAINT fk_ai_kb_document_file FOREIGN KEY (file_id) REFERENCES file_storage (id)
);
