import '../../services/consent_store.dart';

/// 应用内法律文档类型。
enum LegalDocumentType { userAgreement, privacyPolicy }

extension LegalDocumentTypeX on LegalDocumentType {
  /// 文档标题（不带书名号）。
  String get title => switch (this) {
    LegalDocumentType.userAgreement => '用户协议',
    LegalDocumentType.privacyPolicy => '隐私政策',
  };

  /// 文档副标题。
  String get subtitle => switch (this) {
    LegalDocumentType.userAgreement => '使用绵城校园 App 前，请阅读并理解本协议',
    LegalDocumentType.privacyPolicy => '了解我们如何收集、使用与保护你的个人信息',
  };
}

