#!/usr/bin/env python3
"""Build deterministic content-digest URLs for native modules, classic pages and styles.

Run after admin edits; --check fails when checked-in index/manifest need regeneration.
The import map versions transitive module imports as well as the entry script.
"""
from pathlib import Path
import argparse
import hashlib
import json
import re

ROOT = Path(__file__).resolve().parents[1]
ADMIN = ROOT / 'src/main/resources/static/admin'
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
hashes = {}
for path in sorted(ADMIN.rglob('*')):
    if path.is_file() and path.suffix in ('.js', '.css') and path.name != 'asset-manifest.js':
        hashes['/admin/' + path.relative_to(ADMIN).as_posix()] = hashlib.sha256(path.read_bytes()).hexdigest()[:16]
pages = {}
for path in sorted((ADMIN / 'js/pages').glob('*.js')):
    for name in re.findall(r'window\.AdminPages\.([A-Za-z0-9_]+)\s*=', path.read_text()):
        if name in pages:
            raise SystemExit('Duplicate page component: ' + name)
        pages[name] = path.name
manifest = '// Generated by tools/build_admin_assets.py; do not edit.\nexport const PAGE_FILES = ' + json.dumps(pages, indent=2, ensure_ascii=False) + ';\nexport const ASSET_HASHES = ' + json.dumps(hashes, indent=2, ensure_ascii=False) + ';\n'
manifest_path = ADMIN / 'js/core/asset-manifest.js'
hashes['/admin/js/core/asset-manifest.js'] = hashlib.sha256(manifest.encode()).hexdigest()[:16]
index_path = ADMIN / 'index.html'
index = index_path.read_text()
index = re.sub(r'(["\'])(/admin/[^"\'?]+\.(?:js|css))(?:\?v=[^"\']*)?\1', lambda m: m[1] + m[2] + '?v=' + hashes[m[2]] + m[1], index)
imports = {path: path + '?v=' + value for path, value in hashes.items() if path.startswith('/admin/js/core/') or path == '/admin/js/app.js'}
importmap = '<!-- admin-importmap:start -->\n<script type="importmap">' + json.dumps({'imports': imports}, ensure_ascii=False, separators=(',', ':')) + '</script>\n<!-- admin-importmap:end -->'
if '<!-- admin-importmap:start -->' in index:
    index = re.sub(r'<!-- admin-importmap:start -->.*?<!-- admin-importmap:end -->', importmap, index, flags=re.S)
else:
    index = index.replace('</head>', importmap + '\n</head>')
changed = []
for path, value in ((manifest_path, manifest), (index_path, index)):
    if not path.exists() or path.read_text() != value:
        changed.append(str(path.relative_to(ROOT)))
        if not args.check:
            path.write_text(value)
if args.check and changed:
    raise SystemExit('STALE: ' + ', '.join(changed))
print(('CHECK PASS' if args.check else 'BUILD PASS') + ': ' + str(len(hashes)) + ' hashed assets, ' + str(len(pages)) + ' page components')
